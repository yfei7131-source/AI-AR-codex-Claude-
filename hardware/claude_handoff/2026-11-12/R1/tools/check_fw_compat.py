#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Firmware <-> hardware pin-map cross-check.  Read-only on the repo (Codex owns firmware).
Usage: python3 tools/check_fw_compat.py <repo_root> [H02/evt0_core/pinmap_hw.csv]
Exit 0 = no conflicts found, 1 = conflicts / missing inputs.  Writes fw_compat_report.md next to the CSV.
Heuristic: extracts every `#define NAME <gpio>` / GPIO_NUM_<n> / `.pin_x = <n>` from firmware/main and
sdkconfig*; a human must still confirm the name mapping printed in the report."""
import csv, os, re, sys
REQ = ["docs/FEATURES_F01_F22.md", "firmware/main/board.c", "firmware/main/board.h",
       "protocols/DEVICE_MEDIA_V1.md", "protocols/events.schema.json", "mobile/lib"]
KEY = {  # hw net -> substrings expected in the firmware macro name
 "CAM_XCLK_R": ["XCLK"], "CAM_PCLK_R": ["PCLK"], "CAM_VSYNC": ["VSYNC"], "CAM_HREF": ["HREF", "HSYNC"],
 "CAM_SIOD": ["SIOD", "SDA"], "CAM_SIOC": ["SIOC", "SCL"], "CAM_PWR_EN": ["CAM_PWR", "CAM_EN", "PWDN"],
 "CAM_Y2": ["Y2", "CAM_D0"], "CAM_Y3": ["Y3", "CAM_D1"], "CAM_Y4": ["Y4", "CAM_D2"], "CAM_Y5": ["Y5", "CAM_D3"],
 "CAM_Y6": ["Y6", "CAM_D4"], "CAM_Y7": ["Y7", "CAM_D5"], "CAM_Y8": ["Y8", "CAM_D6"], "CAM_Y9": ["Y9", "CAM_D7"],
 "MIC_SD": ["MIC_SD", "MIC_DATA", "I2S_DIN", "I2S_SD", "PDM_DATA"], "MIC_SCK": ["MIC_SCK", "BCLK", "BCK", "PDM_CLK", "I2S_SCK"],
 "MIC_WS": ["MIC_WS", "LRCK", "I2S_WS"], "VBAT_ADC": ["VBAT", "BAT_ADC", "BATTERY"], "KEY_BOOT": ["KEY", "BUTTON", "BTN", "BOOT"],
 "DISP_CS": ["DISP_CS", "LCD_CS"], "DISP_CLK": ["DISP_CLK", "LCD_CLK", "LCD_SCK", "DISP_SCK"], "DISP_RST": ["DISP_RST", "LCD_RST"],
 "DISP_D0": ["DISP_D0", "LCD_D0", "MOSI"], "DISP_D1": ["DISP_D1", "LCD_D1", "MISO"], "DISP_D2": ["DISP_D2", "LCD_D2"],
 "DISP_D3": ["DISP_D3", "LCD_D3"], "DISP_PWR_EN": ["DISP_PWR", "DISP_EN", "LCD_EN", "BL"], "BT_AUD_EN": ["BT_AUD", "AUDIO_EN"],
}
PAT = [re.compile(r"#\s*define\s+(\w+)\s+\(?\s*(?:GPIO_NUM_)?(-?\d+)\s*\)?\s*(?://.*|/\*.*)?$"),
       re.compile(r"\.(\w*(?:pin|gpio|io)\w*)\s*=\s*(?:GPIO_NUM_)?(-?\d+)\s*,"),
       re.compile(r"^(CONFIG_\w*(?:PIN|GPIO)\w*)=(-?\d+)$")]
def main():
    if len(sys.argv) < 2: print(__doc__); return 1
    repo = sys.argv[1]
    pm = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "H02", "evt0_core", "pinmap_hw.csv")
    hw = {int(r["gpio"]): r for r in csv.DictReader(open(pm, encoding="utf-8"))}
    out = ["# fw_compat_report (generated by tools/check_fw_compat.py)", "", "repo: `%s`" % repo, ""]
    bad = 0
    missing = [r for r in REQ if not os.path.exists(os.path.join(repo, r))]
    out.append("## Required repo content"); out += ["- %s `%s`" % ("MISSING" if r in missing else "ok", r) for r in REQ]
    if missing: bad += 1; out.append("\n**Repo incomplete: do NOT freeze GPIO / order parts.**")
    found = []  # (name, gpio, file:line)
    for base in ("firmware/main", "firmware"):
        d = os.path.join(repo, base)
        if not os.path.isdir(d): continue
        for root, dirs, files in os.walk(d):
            dirs[:] = [x for x in dirs if x not in ("build", "managed_components", ".git")]
            if base == "firmware" and root != d: continue
            for fn in files:
                if not (fn.endswith((".c", ".h", ".cpp", ".hpp")) or fn.startswith("sdkconfig") or fn.startswith("Kconfig")): continue
                fp = os.path.join(root, fn)
                for ln, line in enumerate(open(fp, encoding="utf-8", errors="replace"), 1):
                    for pat in PAT:
                        m = pat.search(line.rstrip())
                        if m and re.search(r"PIN|GPIO|IO|CAM|MIC|I2S|I2C|SPI|LCD|DISP|LED|KEY|BTN|BAT|UART|SDA|SCL|CLK", m.group(1), re.I):
                            g = int(m.group(2))
                            if -1 <= g <= 48: found.append((m.group(1), g, "%s:%d" % (os.path.relpath(fp, repo), ln)))
    found = sorted(set(found), key=lambda x: (x[1], x[0]))
    out += ["", "## Firmware pin assignments found (%d)" % len(found), "", "| fw name | gpio | hw net on that gpio | constraint | verdict | source |", "|---|---|---|---|---|---|"]
    used = set()
    for name, g, src in found:
        if g < 0: out.append("| %s | %d | - | - | unused(-1) | %s |" % (name, g, src)); continue
        r = hw.get(g); used.add(g)
        if r is None: v = "CONFLICT: GPIO%d not bonded out on ESP32-S3-WROOM-1" % g; bad += 1; net = "-"; c = ""
        else:
            net, c = r["hw_net"], r["constraint"]
            if "PSRAM" in c or net == "NC": v = "CONFLICT: firmware uses a pin hardware cannot offer"; bad += 1
            elif any(k in name.upper() for k in KEY.get(net, [])): v = "match"
            else: v = "CHECK: name does not obviously match hw net"; bad += 1
        out.append("| %s | %d | %s | %s | %s | %s |" % (name, g, net, c, v, src))
    out += ["", "## Hardware nets with no firmware reference", ""]
    out += ["- GPIO%d %s" % (g, r["hw_net"]) for g, r in sorted(hw.items()) if g not in used and r["hw_net"] != "NC"]
    if not found: bad += 1; out.append("\n**No pin definitions parsed: inspect board.h manually.**")
    rp = os.path.join(os.path.dirname(os.path.abspath(pm)), "fw_compat_report.md")
    open(rp, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("\n".join(out)); print("\nreport ->", rp, "| issues:", bad)
    return 1 if bad else 0
if __name__ == "__main__": sys.exit(main())
